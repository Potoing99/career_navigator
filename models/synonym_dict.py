def preprocess(text):
    """
    텍스트 전처리 함수
    - 등급 키워드 전부 제거 후 유사어 치환 (순서 중요!)
    - 긴 키워드 먼저 제거 (산업기사 → 기사 순서)
    사용: STEP 1 관련학과 판단, STEP 3 유사도 계산
    """
    # 1단계: 등급 키워드 전부 제거 (긴 것부터)
    GRADE_KEYWORDS = ['기술사', '기능장', '산업기사', '기사', '기능사']
    for kw in GRADE_KEYWORDS:
        text = text.replace(kw, '').strip()

    # 2단계: 전부 제거한 뒤 유사어 치환
    for key, value in SYNONYM_DICT.items():
        text = text.replace(key, value)

    return text