def get_related_majors(cert_name: str) -> list:
    """자격증의 관련전공 리스트 반환"""
    entry = CERT_ONTOLOGY.get(cert_name, {})
    return entry.get("관련전공", [])

def get_keywords(cert_name: str) -> list:
    """자격증의 관련키워드 리스트 반환"""
    entry = CERT_ONTOLOGY.get(cert_name, {})
    return entry.get("관련키워드", [])

def get_ncs_dclas(cert_name: str) -> list:
    """자격증의 NCS 세분류 리스트 반환"""
    entry = CERT_ONTOLOGY.get(cert_name, {})
    return entry.get("ncs_dclas", [])

def is_related_major(cert_name: str, major_name: str) -> bool:
    """
    전공명이 해당 자격증의 관련전공인지 판단
    
    1단계: 완전일치 (가장 빠름)
    2단계: 부분일치 (예: '컴퓨터시스템공학' ⊂ '컴퓨터공학')
    3단계: 키워드 매칭 (예: '전산학과' → 키워드 '전산' 포함 여부)
    """
    if not cert_name or not major_name:
        return False
    
    related = get_related_majors(cert_name)
    keywords = get_keywords(cert_name)
    
    if not related:
        return False
    
    major_clean = major_name.strip()
    
    # 1단계: 완전일치
    if major_clean in related:
        return True
    
    # 2단계: 부분일치 (관련전공 문자열이 입력 전공명 안에 포함되거나 반대)
    for r in related:
        if r in major_clean or major_clean in r:
            return True
    
    # 3단계: 키워드 매칭
    for kw in keywords:
        if kw in major_clean:
            return True
    
    return False